class SteamGridDBClient:
    def __init__(self, api_key: str, session: requests.Session | None = None):
        self.api_key = api_key
        self.session = session or requests.Session()

    def _get(self, endpoint: str) -> dict:
        response = self.session.get(
            f"{SGDB_API}{endpoint}", headers={"Authorization": f"Bearer {self.api_key}"}, timeout=30
        )
        response.raise_for_status()
        return response.json()

    def find_game_id(self, app_name: str) -> int | None:
        data = self._get(f"/search/autocomplete/{app_name}")
        results = data.get("data") or []
        return results[0]["id"] if results else None

    def download_first_asset(self, endpoint: str, dest: Path) -> bool:
        data = self._get(endpoint)
        results = data.get("data") or []
        if not results or not results[0].get("url"):
            return False
        response = self.session.get(results[0]["url"], timeout=30)
        response.raise_for_status()
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(response.content)
        return True

    def fetch_artwork(self, app_name: str, appid: int, grid_dir: Path) -> None:
        """Fetch grid/hero/logo/icon art for a shortcut's appid. Already
        having an icon cached is treated as "done" -- this shouldn't hammer
        the API every run against ~20 flatpaks."""
        if (grid_dir / f"{appid}_icon.png").exists():
            return

        game_id = self.find_game_id(app_name)
        if game_id is None:
            logger.error("SteamGridDB: no match found for '%s'", app_name)
            return

        assets = [
            (f"/grids/game/{game_id}?dimensions=600x900", grid_dir / f"{appid}p.png", "portrait grid"),
            (f"/grids/game/{game_id}?dimensions=460x215", grid_dir / f"{appid}.png", "grid"),
            (f"/heroes/game/{game_id}", grid_dir / f"{appid}_hero.png", "hero art"),
            (f"/logos/game/{game_id}", grid_dir / f"{appid}_logo.png", "logo"),
            (f"/icons/game/{game_id}", grid_dir / f"{appid}_icon.png", "icon"),
        ]
        for endpoint, dest, label in assets:
            if not self.download_first_asset(endpoint, dest):
                logger.error("SteamGridDB: failed to fetch %s for '%s'", label, app_name)
        logger.info("SteamGridDB: artwork applied for '%s'", app_name)


def steamgriddb_get_api_key(*, conf_path: Path = STEAMGRIDDB_CONF) -> str | None:
    """Read a configured SteamGridDB API key from the environment or the
    config file. Returns None if not configured -- callers must treat
    that as "skip artwork," not an error; there's no interactive prompt
    here (unlike the original bash), since this is a non-interactive CLI
    context now."""
    env_key = os.environ.get("STEAMGRIDDB_API_KEY")
    if env_key:
        return env_key
    if conf_path.exists():
        for line in conf_path.read_text().splitlines():
            if line.startswith("STEAMGRIDDB_API_KEY="):
                return line.split("=", 1)[1].strip().strip("'\"")
    return None


def save_steamgriddb_api_key(key: str, *, conf_path: Path = STEAMGRIDDB_CONF) -> None:
    conf_path.write_text(f"STEAMGRIDDB_API_KEY={key}\n")
    conf_path.chmod(0o600)


