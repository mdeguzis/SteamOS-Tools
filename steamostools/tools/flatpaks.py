def _github_release_download_url(url: str, name: str, filename_pattern: str | None) -> str:
    is_latest = "latest" in url
    response = requests.get(url, timeout=30)
    response.raise_for_status()
    data = response.json()

    if is_latest:
        assets = data.get("assets", [])
    else:
        prereleases = [r for r in data if r.get("prerelease")]
        assets = prereleases[0]["assets"] if prereleases else []

    urls = [a["browser_download_url"] for a in assets]

    if filename_pattern:
        pattern = re.compile(filename_pattern)
        for candidate in urls:
            if pattern.search(candidate):
                return candidate
    else:
        preference_patterns = [
            r"http.*x.*64.*AppImage$",
            r"http.*AppImage$",
            rf"http.*{re.escape(name)}-.*linux.*x64.*tar\.gz$",
            rf"http.*{re.escape(name)}.*linux.*tar\.gz$",
            rf"http.*{re.escape(name)}.*linux.*tar\.xz$",
        ]
        for pattern_str in preference_patterns:
            pattern = re.compile(pattern_str)
            for candidate in urls:
                if pattern.search(candidate):
                    return candidate

    raise FlatpakInstallError(f"Could not get a download url for {url}")


def resolve_binary_download_url(name: str, url: str, filename_pattern: str | None = None) -> str:
    """Resolve the actual download URL for update_binary's varied input
    shapes: a direct .zip URL, a GitLab releases-API permalink, a GitHub
    releases API URL, or (fallback) the URL itself."""
    if ".zip" in url and "api" not in url:
        return url
    if "gitlab.com/api" in url:
        response = requests.get(url, timeout=30)
        response.raise_for_status()
        data = response.json()
        pattern = re.compile(filename_pattern or rf"{re.escape(name)}.*x64\.AppImage")
        for link in data.get("assets", {}).get("links", []):
            if pattern.search(link.get("name", "")):
                return link["direct_asset_url"]
        raise FlatpakInstallError(f"Could not get a download url for {url}")
    if re.search(r"github\.com.*releases", url):
        return _github_release_download_url(url, name, filename_pattern)
    return url


def update_binary(
    name: str,
    folder_target: str,
    filename_pattern: str,
    url: str,
    dl_type: str,
    *,
    app_loc: Path = APP_LOC,
    download_dir: Path = Path("/tmp"),
) -> Path:
    """Download and install a single-file/archive emulator binary. Handles
    zip/tar.gz/tar.xz/AppImage. Raises FlatpakInstallError if no download
    URL could be resolved."""
    dl_url = resolve_binary_download_url(name, url, filename_pattern or None)
    logger.info("Downloading %s", dl_url)

    response = requests.get(dl_url, stream=True, timeout=60)
    response.raise_for_status()
    dl_filename = dl_url.split("?")[0].rsplit("/", 1)[-1]
    download_path = download_dir / dl_filename
    with download_path.open("wb") as f:
        for chunk in response.iter_content(chunk_size=65536):
            f.write(chunk)

    dest_dir = app_loc / folder_target if folder_target else app_loc
    file_type = dl_type.lower()

    if file_type == "zip":
        dest_dir.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(download_path) as zf:
            zf.extractall(dest_dir)
    elif file_type in ("tar.gz", "tar.xz"):
        dest_dir.mkdir(parents=True, exist_ok=True)
        with tarfile.open(download_path) as tar:
            tar.extractall(dest_dir, filter="data")
        download_path.unlink()
    elif file_type == "appimage":
        dest_dir.mkdir(parents=True, exist_ok=True)
        target = dest_dir / dl_filename
        shutil.move(download_path, target)
        target.chmod(target.stat().st_mode | 0o111)
    else:
        raise FlatpakInstallError(f"Don't know how to handle download type: {dl_type}")

    return dest_dir


