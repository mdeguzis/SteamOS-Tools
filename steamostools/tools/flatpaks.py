# Icon resolution
# ---------------------------------------------------------------------------


def find_flatpak_icon(app_id: str) -> Path | None:
    """Locate an icon for a flatpak app id, preferring larger PNG sizes
    then SVG."""
    roots = [
        Path.home() / ".local" / "share" / "flatpak" / "exports" / "share" / "icons" / "hicolor",
        Path("/var/lib/flatpak/exports/share/icons/hicolor"),
    ]
    for size in ("512x512", "256x256", "128x128", "64x64", "48x48", "32x32"):
        for root in roots:
            matches = list((root / size / "apps").glob(f"{app_id}.*")) if (root / size / "apps").is_dir() else []
            if matches:
                return matches[0]
    for root in roots:
        scalable = root / "scalable" / "apps"
        if scalable.is_dir():
            match = scalable / f"{app_id}.svg"
            if match.exists():
                return match
    return None


def resolve_flatpak_icon(app_id: str, *, icon_cache_dir: Path = ICON_CACHE_DIR) -> str:
    """Wraps find_flatpak_icon, but never hands back an SVG: Steam's
    shortcut icon field can't render SVG. An SVG-only app is rasterized to
    PNG via ImageMagick and cached. Returns "" if no usable icon could be
    resolved (missing icon, or missing ImageMagick for an SVG-only app) --
    a legitimate "leave icon unset" outcome, not an error."""
    icon = find_flatpak_icon(app_id)
    if icon is None:
        return ""
    if icon.suffix != ".svg":
        return str(icon)

    if shutil.which("magick") is None:
        logger.warning(
            "Only an SVG icon is available for %s and ImageMagick (magick) is missing; leaving icon unset.",
            app_id,
        )
        return ""

    converted = icon_cache_dir / f"{app_id}.png"
    if not converted.exists():
        icon_cache_dir.mkdir(parents=True, exist_ok=True)
        result = run(
            ["magick", str(icon), "-background", "none", "-resize", "512x512", str(converted)], check=False
        )
        if result.returncode != 0:
            logger.warning("Failed to convert SVG icon for %s; leaving icon unset.", app_id)
            converted.unlink(missing_ok=True)
            return ""
    return str(converted)


