def steam_add_flatpak_shortcut(app_id: str, display_name: str) -> None:
    vdf_files = steam_shortcuts.find_shortcuts_vdf_files()
    if not vdf_files:
        logger.warning(
            "No shortcuts.vdf found - Steam may not be installed or never launched. Skipping Steam shortcut for %s.",
            display_name,
        )
        return

    api_key = steamgriddb_get_api_key()
    appid = steam_shortcuts.generate_appid("/usr/bin/flatpak", display_name)

    for vdf in vdf_files:
        grid_dir = vdf.parent / "config" / "grid"
        icon = ""
        if api_key:
            SteamGridDBClient(api_key).fetch_artwork(display_name, appid, grid_dir)
            icon_path = grid_dir / f"{appid}_icon.png"
            icon = str(icon_path) if icon_path.exists() else resolve_flatpak_icon(app_id)
        else:
            icon = resolve_flatpak_icon(app_id)

        status = steam_shortcuts.add_or_update_flatpak_shortcut(vdf, app_id, display_name, icon)
        logger.info("Steam shortcut for '%s': %s", display_name, status)


