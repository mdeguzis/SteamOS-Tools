def setup_ludusavi() -> None:
    install_or_update_flatpak("Ludusavi", "com.github.mtkennerly.ludusavi")

    config_dir = Path.home() / ".var" / "app" / "com.github.mtkennerly.ludusavi" / "config" / "ludusavi"
    config_dir.mkdir(parents=True, exist_ok=True)
    (config_dir / "config.yaml").write_text(LUDUSAVI_CONFIG.format(home=Path.home()))

    unit_dir = Path.home() / ".config" / "systemd" / "user"
    unit_dir.mkdir(parents=True, exist_ok=True)
    (unit_dir / "ludusavi-backup.service").write_text(LUDUSAVI_SERVICE)
    (unit_dir / "ludusavi-backup.timer").write_text(LUDUSAVI_TIMER)

    run(["systemctl", "--user", "enable", "ludusavi-backup.timer"])
    run(["systemctl", "--user", "restart", "ludusavi-backup.timer"])


