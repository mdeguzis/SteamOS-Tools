def register_subparser(subparsers) -> None:
    parser = subparsers.add_parser(
        "update-software", help="Flatpak/emulator software updater with Steam shortcut integration"
    )
    sub = parser.add_subparsers(dest="update_software_command", required=True)

    sub.add_parser("all", help="update core software, emulators, user binaries, user flatpaks").set_defaults(
        func=_cmd_all
    )
    sub.add_parser("core", help="update core software (Ludusavi + backup timer)").set_defaults(func=_cmd_core)
    sub.add_parser("emulators", help="update emulator Flatpaks and binaries").set_defaults(func=_cmd_emulators)
    sub.add_parser("user-flatpaks", help="update user Flatpaks").set_defaults(func=_cmd_user_flatpaks)
    sub.add_parser("user-binaries", help="update user binaries").set_defaults(func=_cmd_user_binaries)
    sub.add_parser("remove-deprecated", help="uninstall end-of-life user Flatpaks").set_defaults(
        func=_cmd_remove_deprecated
    )

    flatpaks_parser = subparsers.add_parser("flatpaks", help="browse/manage Flatpaks via Flathub")
    flatpaks_sub = flatpaks_parser.add_subparsers(dest="flatpaks_command", required=True)

    search = flatpaks_sub.add_parser("search", help="search Flathub")
    search.add_argument("query")
    search.set_defaults(func=_cmd_search)

    info = flatpaks_sub.add_parser("info", help="show Flathub app details")
    info.add_argument("app_id")
    info.set_defaults(func=_cmd_info)

    install = flatpaks_sub.add_parser("install", help="install/update a Flatpak by app ID")
    install.add_argument("app_id")
    install.add_argument("--name", default=None, help="display name for the Steam shortcut (default: app_id)")
    install.set_defaults(func=_cmd_flatpak_install)

    flatpaks_sub.add_parser("list", help="list installed Flatpaks").set_defaults(func=_cmd_flatpak_list)


