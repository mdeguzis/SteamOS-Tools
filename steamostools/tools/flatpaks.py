def install_or_update_flatpak(name: str, app_id: str) -> None:
    """Update app_id if installed, otherwise install it from Flathub.
    Raises FlatpakInstallError if both fail."""
    logger.info("Installing/updating %s", name)
    update_result = run(["flatpak", "--user", "update", app_id, "-y"], check=False)
    if update_result.returncode != 0:
        install_result = run(
            ["flatpak", "install", "--user", "-y", "--noninteractive", "flathub", app_id], check=False
        )
        if install_result.returncode != 0:
            raise FlatpakInstallError(f"Failed to install Flatpak {app_id}")

    run(["flatpak", "override", app_id, "--filesystem=host", "--user"])
    run(["flatpak", "override", app_id, "--share=network", "--user"])

    steam_add_flatpak_shortcut(app_id, name)


def list_installed() -> list[dict]:
    """Return installed Flatpak apps as [{"id", "name", "description", "version"}, ...]."""
    result = run(
        ["flatpak", "list", "--app", "--columns=application,name,description,version"], check=False
    )
    apps = []
    for line in result.stdout.splitlines():
        parts = line.split("\t")
        if len(parts) >= 4:
            apps.append({"id": parts[0], "name": parts[1], "description": parts[2], "version": parts[3]})
    return apps


def remove_deprecated_flatpaks() -> list[str]:
    """Uninstall user Flatpaks Flathub marks end-of-life. Returns the app
    IDs removed (empty list is a legitimate "nothing deprecated" outcome)."""
    result = run(["flatpak", "list", "--user", "--app", "--columns=application,name,options"], check=False)
    removed = []
    for line in result.stdout.splitlines():
        parts = line.split("\t")
        if len(parts) < 3 or "eol=" not in parts[2]:
            continue
        app_id, app_name, options = parts[0], parts[1], parts[2]
        reason = options.split("eol=", 1)[1]
        logger.info("Removing deprecated Flatpak: %s (%s) - %s", app_name, app_id, reason)
        uninstall_result = run(["flatpak", "uninstall", "--user", "-y", app_id], check=False)
        if uninstall_result.returncode == 0:
            removed.append(app_id)
        else:
            logger.error("Failed to uninstall %s", app_id)
    return removed


