def _cmd_search(args) -> int:
    hits = FlathubClient().search(args.query)
    for hit in hits:
        print(f"{hit.get('app_id')}\t{hit.get('name')}\t{hit.get('summary', '')}")
    return 0


def _cmd_info(args) -> int:
    info = FlathubClient().app_info(args.app_id)
    for key in ("name", "summary", "developer_name", "project_license", "installs_last_month"):
        print(f"{key}: {info.get(key, 'N/A')}")
    return 0


def _cmd_flatpak_install(args) -> int:
    install_or_update_flatpak(args.name or args.app_id, args.app_id)
    return 0


def _cmd_flatpak_list(args) -> int:
    for app in list_installed():
        print(f"{app['id']}\t{app['name']}\t{app['version']}")
    return 0
